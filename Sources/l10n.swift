import Foundation

// QuotaMeter localization (zh source strings as keys, en/ja tables).
// Language choice lives in UserDefaults "qm_lang": auto | zh | en | ja.
// Changing it relaunches the app, so every label — including the ones
// built once at launch — comes up in the new language. Stored data
// (ping history entries, thread names, log lines) stays in canonical
// Chinese and is translated at render time where it is user-visible.

enum AppLang: String { case zh, en, ja }

var currentLang: AppLang {
    switch UserDefaults.standard.string(forKey: "qm_lang") ?? "auto" {
    case "zh": return .zh
    case "en": return .en
    case "ja": return .ja
    default:
        let p = Locale.preferredLanguages.first ?? "zh"
        if p.hasPrefix("ja") { return .ja }
        if p.hasPrefix("en") { return .en }
        return .zh
    }
}

var currentLocale: Locale {
    switch currentLang {
    case .zh: return Locale(identifier: "zh_CN")
    case .en: return Locale(identifier: "en_US")
    case .ja: return Locale(identifier: "ja_JP")
    }
}

func L(_ key: String, _ args: CVarArg...) -> String {
    let t: String
    switch currentLang {
    case .zh: t = key
    case .en: t = enTable[key] ?? key
    case .ja: t = jaTable[key] ?? key
    }
    return args.isEmpty ? t : String(format: t, arguments: args)
}

/// Ping history entries are stored canonically (Chinese tokens, "M月d日"
/// dates). Translate the tokens — and the date separators for English —
/// when rendering.
func localizedHistoryEntry(_ s: String) -> String {
    if currentLang == .zh { return s }
    var t = s
    if currentLang == .en {
        t = t.replacingOccurrences(of: "月", with: "/").replacingOccurrences(of: "日", with: "")
        for (a, b) in [("新建专用对话", "New dedicated conversation"), ("自动", "Auto"), ("手动", "Manual"),
                       ("接口", "API"), ("命令行", "CLI"), ("成功", "Success"), ("失败", "Failed")] {
            t = t.replacingOccurrences(of: a, with: b)
        }
    } else {
        for (a, b) in [("新建专用对话", "専用会話を作成"), ("自动", "自動"), ("手动", "手動"),
                       ("接口", "API"), ("命令行", "CLI"), ("失败", "失敗")] {
            t = t.replacingOccurrences(of: a, with: b)
        }
    }
    return t
}

